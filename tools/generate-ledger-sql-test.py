#!/usr/bin/env python3
"""Generates supabase/tests/phase3_ledger.sql from tests/fixtures/posting-cases.json.
Optional: only needed if you change the fixtures. Run from the project folder:  python tools/generate-ledger-sql-test.py"""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
doc = json.load(open(os.path.join(root, "tests/fixtures/posting-cases.json"), encoding="utf-8"))
cases = [c for c in doc["cases"] if c.get("rpc")]   # cases with rpc = null are covered elsewhere

def lit(v):
    if v is None: return "NULL"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return str(v)
    if isinstance(v, str) and v.startswith("$"): return v[1:].lower()      # $C1 -> c1 (a uuid variable)
    return "'" + v.replace("'", "''") + "'"

DEFAULTS = {"post_mobile_load": {"p_load_product_id": None}, "post_expense": {"p_category_id": None}}

def expected_array(lines):
    parts = []
    for l in lines:
        cust = "c1::text" if l["customer"] == "C1" else "''"
        parts.append(f"'{l['account']}|' || {cust} || '|{l['amountCents']}'")
    return "array[" + ", ".join(parts) + "]"

def as_user(var):
    return (f"  perform set_config('request.jwt.claim.sub', {var}::text, true);\n"
            f"  perform set_config('request.jwt.claims', json_build_object('sub', {var}::text, 'role', 'authenticated')::text, true);\n")

out = []
w = out.append
w("""-- Kabisera Ledger · Phase 3 ledger-engine checks  (GENERATED by tools/generate-ledger-sql-test.py)
--
-- WRITTEN BUT NOT EXECUTED by the assistant (no PostgreSQL was available).
-- Run on a FRESH local database (`npm run db:reset`) BEFORE entering real data, in Studio's SQL editor.
-- It posts every case from tests/fixtures/posting-cases.json through the real database functions, as a signed-in
-- owner with the real grants, and compares the ledger lines with the hand-derived answers. It then checks
-- idempotency, overdraft protection, permissions, over-repayment and voids.
-- Everything is rolled back; the script ENDS WITH AN ERROR ON PURPOSE and that message is the report:
-- first line must say 0 failure(s), every line must start with PASS.

do $$
declare
  report text := '';
  failures int;
  u_owner uuid := gen_random_uuid();
  u_staff uuid := gen_random_uuid();   -- transactions.record + repayments.record + customers.view
  u_none  uuid := gen_random_uuid();   -- no permissions
  c1      uuid := gen_random_uuid();
  idem_dup uuid := gen_random_uuid();
  v_tx uuid; v_ref text; v_dup boolean;
  tx_credit uuid; tx_repay uuid; tx_dup uuid; tx_staff uuid;
  v_actual text[]; v_expected text[];
  n bigint; v bigint;
begin
  select count(*) into n from public.ledger_lines;
  report := report || case when n = 0 then 'PASS' else 'FAIL (database not fresh: run npm run db:reset first)' end
            || ': the ledger starts empty (no invented opening balances)' || E'\\n';

  insert into auth.users (id, email) values
    (u_owner, 'p3-owner@example.invalid'), (u_staff, 'p3-staff@example.invalid'), (u_none, 'p3-none@example.invalid');
  insert into public.profiles (id, display_name, role, permissions) values
    (u_owner, 'P3 Owner', 'owner', '{}'),
    (u_staff, 'P3 Staff', 'staff', array['transactions.record', 'repayments.record', 'customers.view']),
    (u_none,  'P3 None',  'staff', '{}');
  insert into public.customers (id, display_name) values (c1, 'P3 Customer');

  -- everything below runs as the signed-in owner with the real API privileges
""")
w(as_user("u_owner"))
w("  set local role authenticated;\n\n")

# --- the fixture cases
totals = {}
for i, c in enumerate(cases):
    fn = c["rpc"]["fn"]
    args = {"p_idempotency_key": "$idem_dup" if i == 1 else None}
    call_args = []
    idem = "idem_dup" if i == 1 else "gen_random_uuid()"
    call_args.append(f"p_idempotency_key => {idem}")
    merged = {**DEFAULTS.get(fn, {}), **c["rpc"]["args"]}
    for k, v in merged.items():
        call_args.append(f"{k} => {lit(v)}")
    for l in c["lines"]:
        totals[l["account"]] = totals.get(l["account"], 0) + l["amountCents"]
    capture = ""
    if i == 2: capture = "tx_credit := v_tx;"          # case 3: the cash-in with an unpaid balance
    if fn == "post_repayment": capture = "tx_repay := v_tx;"
    if i == 1: capture = "tx_dup := v_tx;"
    w(f"  -- case {i+1}: {c['name']}\n  begin\n")
    w(f"    select t.tx_id into v_tx from public.{fn}({', '.join(call_args)}) t;\n")
    if capture: w(f"    {capture}\n")
    w(f"    select array(select x from unnest({expected_array(c['lines'])}) x order by x) into v_expected;\n")
    w("    select array(select a.code || '|' || coalesce(l.customer_id::text, '') || '|' || l.amount_cents::text\n"
      "                   from public.ledger_lines l join public.accounts a on a.id = l.account_id\n"
      "                   join public.journal_entries je on je.id = l.entry_id where je.transaction_id = v_tx order by 1) into v_actual;\n")
    name = c["name"].replace("'", "''")
    w(f"    report := report || case when v_actual = v_expected then 'PASS' else 'FAIL (got ' || array_to_string(v_actual, ' ; ') || ')' end || ': {name}' || E'\\n';\n")
    w(f"  exception when others then\n    report := report || 'FAIL (error: ' || sqlerrm || '): {name}' || E'\\n';\n  end;\n\n")

# --- balances after all cases
w("  -- the account balances equal the sum of the hand-derived cases\n")
for code, total in sorted(totals.items()):
    w(f"  select net_debit_cents into v from public.account_balances where code = '{code}';\n")
    w(f"  report := report || case when v = {total} then 'PASS' else 'FAIL (got ' || v || ')' end || ': balance of {code} = {total} (net debits)' || E'\\n';\n")
w("""  select coalesce(sum(amount_cents), 0) into v from public.ledger_lines;
  report := report || case when v = 0 then 'PASS' else 'FAIL' end || ': debits and credits across the whole ledger sum to zero' || E'\\n';

  select outstanding_cents into v from public.customer_receivable_balances where customer_id = c1;
  report := report || case when v = 76000 then 'PASS' else 'FAIL (got ' || v || ')' end || ': the ledger says the customer owes 760.00 (520 + 40 + 500 - 300)' || E'\\n';
  select coalesce(sum(outstanding_cents), 0) into v from public.debt_balances where customer_id = c1;
  report := report || case when v = 76000 then 'PASS' else 'FAIL (got ' || v || ')' end || ': the debt records agree with the ledger' || E'\\n';
  select count(*) into n from public.debts where customer_id = c1;
  report := report || case when n = 3 then 'PASS' else 'FAIL (got ' || n || ')' end || ': three debts were created (credit sale, credit load, cash advance)' || E'\\n';
  select b.outstanding_cents into v from public.debt_balances b join public.debts d on d.id = b.debt_id
   where d.source_transaction_id = tx_credit;
  report := report || case when v = 22000 then 'PASS' else 'FAIL (got ' || v || ')' end || ': the repayment went to the OLDEST debt first (520.00 - 300.00)' || E'\\n';
  select count(*) into n from public.audit_log where entity_type = 'transactions' and action = 'transaction.post';
  report := report || case when n = """ + str(len(cases)) + """ then 'PASS' else 'FAIL (got ' || n || ')' end || ': every posted transaction is audited' || E'\\n';
  select tx_ref into v_ref from public.post_expense(gen_random_uuid(), null, 100, 'cash') ;
  report := report || case when v_ref ~ '^KL-[0-9]{8}-[0-9]{4}$' then 'PASS' else 'FAIL (got ' || v_ref || ')' end || ': references look like KL-YYYYMMDD-NNNN' || E'\\n';

  -- idempotency: the same key returns the original record and posts nothing new
  select count(*) into n from public.ledger_lines;
  select t.tx_id, t.was_duplicate into v_tx, v_dup from public.post_cash_in(
    p_idempotency_key => idem_dup, p_customer_id => NULL, p_principal_cents => 100000, p_fee_cents => 2000, p_fee_mode => 'on_top') t;
  report := report || case when v_tx = tx_dup and v_dup then 'PASS' else 'FAIL' end || ': repeating a request returns the original transaction' || E'\\n';
  select count(*) - n into v from public.ledger_lines;
  report := report || case when v = 0 then 'PASS' else 'FAIL' end || ': ...and posts nothing a second time' || E'\\n';

  -- opening balances can only be entered once
  begin
    perform public.post_opening_balances(gen_random_uuid(), 100, 0, 0);
    report := report || 'FAIL: opening balances were entered twice' || E'\\n';
  exception when check_violation then
    report := report || 'PASS: opening balances cannot be entered twice' || E'\\n';
  end;

  -- validation
  begin
    perform public.post_cash_in(gen_random_uuid(), NULL, 0, 0, 'on_top');
    report := report || 'FAIL: a zero amount was accepted' || E'\\n';
  exception when check_violation then
    report := report || 'PASS: a zero amount is rejected' || E'\\n';
  end;
  begin
    perform public.post_cash_in(gen_random_uuid(), NULL, 1000, 0, 'on_top', 500);
    report := report || 'FAIL: an unpaid amount with no customer was accepted' || E'\\n';
  exception when check_violation then
    report := report || 'PASS: an unpaid amount needs a customer' || E'\\n';
  end;

  -- overdraft protection
  begin
    perform public.post_cash_out(gen_random_uuid(), NULL, 999999999, 0, 'deducted');
    report := report || 'FAIL: the cash drawer was overdrawn' || E'\\n';
  exception when check_violation then
    report := report || 'PASS: the cash drawer cannot be overdrawn' || E'\\n';
  end;

  -- repayment larger than the debt
  begin
    perform public.post_repayment(gen_random_uuid(), c1, 10000000, 'cash');
    report := report || 'FAIL: a repayment larger than the debt was accepted' || E'\\n';
  exception when check_violation then
    report := report || 'PASS: a repayment cannot exceed what the customer owes' || E'\\n';
  end;

""")
w("  -- ----------------------------------------------------------------- staff permissions\n")
w(as_user("u_none"))
w("""  begin
    perform public.post_cash_in(gen_random_uuid(), NULL, 1000, 0, 'on_top');
    report := report || 'FAIL: a person with no permissions posted a cash-in' || E'\\n';
  exception when insufficient_privilege then
    report := report || 'PASS: a person with no permissions cannot post' || E'\\n';
  end;
""")
w(as_user("u_staff"))
w("""  select t.tx_id into tx_staff from public.post_cash_in(gen_random_uuid(), NULL, 1000, 20, 'on_top') t;
  report := report || case when tx_staff is not null then 'PASS' else 'FAIL' end || ': staff with transactions.record can post a cash-in' || E'\\n';
  begin
    perform public.post_cash_in(gen_random_uuid(), NULL, 1000, 20, 'on_top', 0, 0, NULL, NULL, now() - interval '1 day');
    report := report || 'FAIL: staff back-dated a transaction' || E'\\n';
  exception when insufficient_privilege then
    report := report || 'PASS: staff cannot choose a different date or time' || E'\\n';
  end;
  begin
    perform public.post_expense(gen_random_uuid(), NULL, 100, 'cash');
    report := report || 'FAIL: staff recorded an expense' || E'\\n';
  exception when insufficient_privilege then
    report := report || 'PASS: staff cannot record expenses' || E'\\n';
  end;
  begin
    perform public.post_float_adjustment(gen_random_uuid(), 'transfer_cash_to_gcash', 100);
    report := report || 'FAIL: staff adjusted a balance' || E'\\n';
  exception when insufficient_privilege then
    report := report || 'PASS: staff cannot adjust balances' || E'\\n';
  end;
  begin
    perform public.post_opening_balances(gen_random_uuid(), 1, 0, 0);
    report := report || 'FAIL: staff entered opening balances' || E'\\n';
  exception when insufficient_privilege then
    report := report || 'PASS: staff cannot enter opening balances' || E'\\n';
  end;
  begin
    perform public.void_transaction(tx_staff, 'staff trying to void');
    report := report || 'FAIL: staff voided a transaction' || E'\\n';
  exception when insufficient_privilege then
    report := report || 'PASS: staff cannot void' || E'\\n';
  end;
  begin
    perform public.request_void(tx_staff, 'entered the wrong amount');
    report := report || 'PASS: staff can request a void of their own transaction' || E'\\n';
  exception when others then
    report := report || 'FAIL (error: ' || sqlerrm || '): requesting a void' || E'\\n';
  end;
  begin
    perform public.request_void(tx_staff, 'asking twice');
    report := report || 'FAIL: a second void request was accepted' || E'\\n';
  exception when check_violation then
    report := report || 'PASS: a void can be requested only once' || E'\\n';
  end;

  -- ----------------------------------------------------------------- voids (owner)
""")
w(as_user("u_owner"))
w("""  begin
    perform public.void_transaction(tx_credit, 'trying to void while a repayment depends on it');
    report := report || 'FAIL: voided a credit sale that already has a repayment' || E'\\n';
  exception when check_violation then
    report := report || 'PASS: a debt with repayments cannot be voided until the repayments are voided' || E'\\n';
  end;
  begin
    perform public.void_transaction(tx_repay, 'x');
    report := report || 'FAIL: a void without a real reason was accepted' || E'\\n';
  exception when check_violation then
    report := report || 'PASS: a void needs a reason' || E'\\n';
  end;
  perform public.void_transaction(tx_repay, 'customer paid by mistake');
  select outstanding_cents into v from public.customer_receivable_balances where customer_id = c1;
  report := report || case when v = 106000 then 'PASS' else 'FAIL (got ' || v || ')' end || ': voiding the repayment puts 300.00 back on the ledger' || E'\\n';
  select coalesce(sum(outstanding_cents), 0) into v from public.debt_balances where customer_id = c1;
  report := report || case when v = 106000 then 'PASS' else 'FAIL (got ' || v || ')' end || ': ...and on the debt records' || E'\\n';
  perform public.void_transaction(tx_credit, 'the sale was cancelled');
  select outstanding_cents into v from public.customer_receivable_balances where customer_id = c1;
  report := report || case when v = 54000 then 'PASS' else 'FAIL (got ' || v || ')' end || ': voiding the credit sale removes its 520.00 from the ledger' || E'\\n';
  select coalesce(sum(outstanding_cents), 0) into v from public.debt_balances where customer_id = c1;
  report := report || case when v = 54000 then 'PASS' else 'FAIL (got ' || v || ')' end || ': ...and its debt is worth nothing' || E'\\n';
  begin
    perform public.void_transaction(tx_credit, 'again');
    report := report || 'FAIL: a transaction was voided twice' || E'\\n';
  exception when check_violation then
    report := report || 'PASS: a transaction cannot be voided twice' || E'\\n';
  end;
  select count(*) into n from public.journal_entries where kind = 'reversal';
  report := report || case when n = 2 then 'PASS' else 'FAIL (got ' || n || ')' end || ': each void added one mirror entry; the originals remain' || E'\\n';
  select coalesce(sum(amount_cents), 0) into v from public.ledger_lines;
  report := report || case when v = 0 then 'PASS' else 'FAIL' end || ': the ledger still sums to zero after voids' || E'\\n';

  -- the owner override with a reason (last, because it overdraws the drawer on purpose)
  begin
    perform public.post_cash_out(gen_random_uuid(), NULL, 999999999, 0, 'deducted', 0, NULL, NULL, NULL, 'phase 3 test override');
    report := report || 'PASS: the owner can override the overdraft protection with a reason' || E'\\n';
  exception when others then
    report := report || 'FAIL (error: ' || sqlerrm || '): the owner override did not work' || E'\\n';
  end;
  select count(*) into n from public.audit_log where reason = 'phase 3 test override';
  report := report || case when n >= 1 then 'PASS' else 'FAIL' end || ': the override and its reason are in the audit log' || E'\\n';

  reset role;
  failures := (length(report) - length(replace(report, 'FAIL', ''))) / 4;
  raise exception E'PHASE 3 CHECKS: % failure(s). This error is intentional so that nothing is saved.\\n%', failures, report;
end;
$$;
""")
path = os.path.join(root, "supabase/tests/phase3_ledger.sql")
open(path, "w", encoding="utf-8").write("".join(out))
print("wrote", path, len("".join(out).splitlines()), "lines;", len(cases), "cases")
